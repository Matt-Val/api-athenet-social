-- Esquema inicial de MS-Social. Primer servicio de Athenet con una entidad de
-- usuario propia: Cognito es el proveedor de identidad, pero NO es una base de
-- datos consultable desde el dominio, asi que se guarda una copia local de los
-- datos de perfil (mismo criterio que delegate_display_name en Competencia).

-- Perfil local del usuario publico autenticado con Cognito.
--   cognito_sub : identidad tecnica, SIEMPRE derivada del claim "sub" del token
--                 ya validado. Nunca se acepta desde el cuerpo de una peticion.
--
--   email       : clave natural estable. Si el User Pool se recrea (el laboratorio
--                 de AWS Academy puede borrar recursos entre sesiones), el sub
--                 cambia y el email no: por eso es UNIQUE y permite re-vincular
--                 el perfil en vez de dejar sus likes huerfanos.

CREATE TABLE user_profile (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    cognito_sub   VARCHAR(36)  NOT NULL,
    email         VARCHAR(320) NOT NULL,
    given_name    VARCHAR(128),
    family_name   VARCHAR(128),
    display_name  VARCHAR(256) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    last_seen_at  TIMESTAMPTZ,
    CONSTRAINT pk_user_profile             PRIMARY KEY (id),
    CONSTRAINT uk_user_profile_cognito_sub UNIQUE (cognito_sub),
    CONSTRAINT uk_user_profile_email       UNIQUE (email)
);

-- "Me gusta". target_type discrimina el tipo de recurso y target_id
-- es un ID de otro servicio: sin clave foranea, porque la decision D2 de
-- la arquitectura prohibe acoplarse al esquema de otra base. Es VARCHAR porque la
-- identidad publica de un evento es su internalId ("EVT-42"), no un numero.
CREATE TABLE user_likes (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_profile_id BIGINT       NOT NULL,
    target_type     VARCHAR(20)  NOT NULL,
    target_id       VARCHAR(64)  NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_user_likes         PRIMARY KEY (id),
    CONSTRAINT uk_user_likes_once    UNIQUE (user_profile_id, target_type, target_id),
    CONSTRAINT fk_user_likes_profile FOREIGN KEY (user_profile_id)
        REFERENCES user_profile (id) ON DELETE CASCADE
);

-- Para contar los likes de un recurso sin recorrer la tabla entera.
CREATE INDEX idx_user_likes_target ON user_likes (target_type, target_id);

-- Equipos favoritos. team_id e institution_id son IDs de MS-Instituciones.
-- team_name e institution_name son copias (snapshot) para poder dibujar la lista
-- aunque Instituciones no responda: sin ellos, la pantalla de favoritos dependeria
-- de que otro microservicio este arriba.
CREATE TABLE user_favorite_teams (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_profile_id  BIGINT       NOT NULL,
    team_id          BIGINT       NOT NULL,
    team_name        VARCHAR(256),
    institution_id   BIGINT,
    institution_name VARCHAR(256),
    created_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_user_favorite_teams         PRIMARY KEY (id),
    CONSTRAINT uk_user_favorite_teams_once    UNIQUE (user_profile_id, team_id),
    CONSTRAINT fk_user_favorite_teams_profile FOREIGN KEY (user_profile_id)
        REFERENCES user_profile (id) ON DELETE CASCADE
);